export type ControllerMode = 'autonomous' | 'legacy' | 'islanded';

export type WeatherHorizon = 'clear' | 'intermittent' | 'storm';

export interface MicrogridState {
  // Input settings & constraints
  irradiance: number;           // W/m^2 (0 - 1000)
  baseFacilityLoad: number;     // kW (20 - 150)
  minSocConstraint: number;     // % (10 - 30)
  weatherHorizon: WeatherHorizon;
  controllerMode: ControllerMode;
  isCloudCoverChaosActive: boolean;
  cloudChaosCountdown: number;  // seconds remaining

  // Live real-time power dispatch telemetry (kW)
  solarKW: number;
  facilityLoadKW: number;
  netKW: number;                // Solar - Load
  bessKW: number;               // > 0 = discharging to load, < 0 = charging from solar
  gridKW: number;               // > 0 = import from grid, < 0 = export to grid
  dieselKW: number;             // kW generated by backup diesel
  dieselStatus: 'SUPPRESSED' | 'ACTIVE' | 'STANDBY';

  // Battery Energy Storage System (BESS) state
  bessSoC: number;              // State of Charge % (0 - 100)
  bessCapacityKWh: number;      // Rated capacity (200 kWh)
  bessHealthPct: number;        // SOH % (e.g. 99.4%)
  bessDoD: number;              // Current Depth of Discharge %
  bessTempC: number;            // Temperature in Celsius
  bessMicroCycles: number;      // Count of micro-cycles prevented
  bessCRate: number;            // Current C-rate

  // Impact & Accounting KPIs
  cumulativeCo2SavedKg: number;
  dieselHoursReducedPct: number;
  batteryLifespanExtPct: number;
  costSavingsUSD: number;
  cleanEnergyRatioPct: number;

  // Edge Hardware & Model Metrics
  inferenceLatencyMs: number;
  modelJitterMs: number;
  simulatedTimeMinutes: number; // 0 to 1440 (24h clock)
}

export interface LedgerLog {
  id: string;
  timestamp: string;
  type: 'ONNX-AGENT' | 'DISPATCH' | 'PROTECT' | 'CARBON' | 'ALERT';
  message: string;
  deltaCo2: number;
  badgeColor: string;
}

export interface ForecastPoint {
  timeStr: string;
  slotIndex: number;
  predictedSolar: number;
  actualSolar: number;
  predictedLoad: number;
  actualLoad: number;
  projectedSoc: number;
  bessDispatchKW: number;
  gridImportKW: number;
  dieselKW: number;
}
